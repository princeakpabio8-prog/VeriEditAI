import { useState } from "react";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Badge } from "@/components/ui/badge";
import { useToast } from "@/hooks/use-toast";
import { Download, FileText, Image, Loader2 } from "lucide-react";
import jsPDF from 'jspdf';
import { safeLower } from "@/lib/utils";

interface VerificationExportProps {
  verificationId: string;
  trustScore: number;
  status: string;
  summary: string;
  sources: Array<{
    title: string;
    url: string;
    reliability_score?: number;
  }>;
  content: string;
  processingTime?: number;
}

export function VerificationExport({
  verificationId,
  trustScore,
  status,
  summary,
  sources,
  content,
  processingTime
}: VerificationExportProps) {
  const [exporting, setExporting] = useState(false);
  const [exportFormat, setExportFormat] = useState<'pdf' | 'json' | 'csv'>('pdf');
  const { toast } = useToast();

  const generatePDF = async () => {
    setExporting(true);
    try {
      const pdf = new jsPDF();
      const pageWidth = pdf.internal.pageSize.getWidth();
      const margin = 20;
      let yPosition = margin;

      // Helper function to add text with word wrapping
      const addText = (text: string, fontSize = 12, isBold = false) => {
        if (isBold) {
          pdf.setFont("helvetica", "bold");
        } else {
          pdf.setFont("helvetica", "normal");
        }
        pdf.setFontSize(fontSize);
        
        const lines = pdf.splitTextToSize(text, pageWidth - 2 * margin);
        
        // Check if we need a new page
        if (yPosition + (lines.length * fontSize * 0.4) > pdf.internal.pageSize.getHeight() - margin) {
          pdf.addPage();
          yPosition = margin;
        }
        
        pdf.text(lines, margin, yPosition);
        yPosition += lines.length * fontSize * 0.4 + 5;
      };

      // Header
      addText("CONTENT VERIFICATION REPORT", 20, true);
      yPosition += 10;

      // Verification Details
      addText("Verification Details", 16, true);
      addText(`Verification ID: ${verificationId}`, 12);
      addText(`Date: ${new Date().toLocaleDateString()}`, 12);
      addText(`Status: ${String(status || 'unknown').toUpperCase()}`, 12);
      addText(`Trust Score: ${trustScore}%`, 12);
      if (processingTime) {
        addText(`Processing Time: ${processingTime}ms`, 12);
      }
      yPosition += 10;

      // Content Analysis
      addText("Content Analyzed", 16, true);
      addText(content.substring(0, 500) + (content.length > 500 ? '...' : ''), 10);
      yPosition += 10;

      // Summary
      addText("Analysis Summary", 16, true);
      addText(summary, 12);
      yPosition += 10;

      // Sources
      if (sources.length > 0) {
        addText("Verification Sources", 16, true);
        sources.forEach((source, index) => {
          addText(`${index + 1}. ${source.title}`, 12, true);
          addText(`   URL: ${source.url}`, 10);
          if (source.reliability_score) {
            addText(`   Reliability: ${source.reliability_score}%`, 10);
          }
          yPosition += 5;
        });
      }

      // Footer
      yPosition = pdf.internal.pageSize.getHeight() - 30;
      pdf.setFontSize(8);
      pdf.setFont("helvetica", "normal");
      pdf.text(
        "This report was generated by AI-powered content verification system.",
        margin,
        yPosition
      );

      // Save the PDF
      pdf.save(`verification-report-${verificationId}.pdf`);

      toast({
        title: "Export Complete",
        description: "PDF report generated successfully",
      });

    } catch (error) {
      console.error('PDF export error:', error);
      toast({
        title: "Export Failed", 
        description: "Failed to generate PDF report",
        variant: "destructive",
      });
    } finally {
      setExporting(false);
    }
  };

  const generateJSON = () => {
    const data = {
      verificationId,
      timestamp: new Date().toISOString(),
      trustScore,
      status,
      summary,
      content,
      sources,
      processingTime,
      metadata: {
        exportFormat: 'json',
        version: '1.0'
      }
    };

    const blob = new Blob([JSON.stringify(data, null, 2)], { 
      type: 'application/json' 
    });
    
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `verification-${verificationId}.json`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    toast({
      title: "Export Complete",
      description: "JSON data exported successfully",
    });
  };

  const generateCSV = () => {
    const csvData = [
      ['Field', 'Value'],
      ['Verification ID', verificationId],
      ['Date', new Date().toISOString()],
      ['Trust Score', `${trustScore}%`],
      ['Status', status],
      ['Processing Time', `${processingTime || 0}ms`],
      ['Summary', summary.replace(/,/g, ';')], // Replace commas to avoid CSV issues
      ['Content', content.substring(0, 500).replace(/,/g, ';')],
      ['', ''],
      ['Sources', ''],
      ...sources.map((source, index) => [
        `Source ${index + 1}`, 
        `${source.title} - ${source.url} (Reliability: ${source.reliability_score || 'N/A'}%)`
      ])
    ];

    const csvContent = csvData.map(row => 
      row.map(field => `"${field.toString().replace(/"/g, '""')}"`).join(',')
    ).join('\n');

    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `verification-${verificationId}.csv`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    toast({
      title: "Export Complete",
      description: "CSV data exported successfully",
    });
  };

  const handleExport = async () => {
    switch (exportFormat) {
      case 'pdf':
        await generatePDF();
        break;
      case 'json':
        generateJSON();
        break;
      case 'csv':
        generateCSV();
        break;
    }
  };

  const getStatusColor = (status: string | undefined) => {
    if (!status) return 'bg-gray-500/10 text-gray-700 border-gray-200';
    
    const safeStatus = safeLower(status);
    switch (safeStatus) {
      case 'verified':
      case 'completed':
        return 'bg-green-500/10 text-green-700 border-green-200';
      case 'disputed':
      case 'mixed':
        return 'bg-yellow-500/10 text-yellow-700 border-yellow-200';
      case 'false':
      case 'failed':
        return 'bg-red-500/10 text-red-700 border-red-200';
      default:
        return 'bg-gray-500/10 text-gray-700 border-gray-200';
    }
  };

const getTrustScoreColor = (score: number | undefined) => {
  if (!score) return 'text-gray-600';
  if (score >= 80) return 'text-green-600';
  if (score >= 60) return 'text-yellow-600';
  return 'text-red-600';
};

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          <Download className="h-5 w-5" />
          Export Verification Report
        </CardTitle>
        <CardDescription>
          Download your verification results in multiple formats
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-6">
        {/* Verification Summary */}
        <div className="p-4 border rounded-lg bg-muted/30">
          <div className="grid grid-cols-2 md:grid-cols-4 gap-4 mb-4">
            <div>
              <p className="text-sm text-muted-foreground">Trust Score</p>
              <p className={`text-lg font-semibold ${getTrustScoreColor(trustScore)}`}>
                {trustScore}%
              </p>
            </div>
            <div>
              <p className="text-sm text-muted-foreground">Status</p>
              <Badge variant="outline" className={getStatusColor(status)}>
                {String(status || 'unknown')}
              </Badge>
            </div>
            <div>
              <p className="text-sm text-muted-foreground">Sources</p>
              <p className="text-lg font-semibold">{sources.length}</p>
            </div>
            <div>
              <p className="text-sm text-muted-foreground">ID</p>
              <p className="text-sm font-mono">{verificationId.slice(0, 8)}...</p>
            </div>
          </div>
          
          <div>
            <p className="text-sm text-muted-foreground mb-2">Summary</p>
            <p className="text-sm">{summary.substring(0, 200)}...</p>
          </div>
        </div>

        {/* Export Options */}
        <div className="space-y-4">
          <div>
            <label className="text-sm font-medium mb-2 block">Export Format</label>
            <Select value={exportFormat} onValueChange={(value: any) => setExportFormat(value)}>
              <SelectTrigger>
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="pdf">
                  <div className="flex items-center gap-2">
                    <FileText className="h-4 w-4" />
                    PDF Report
                  </div>
                </SelectItem>
                <SelectItem value="json">
                  <div className="flex items-center gap-2">
                    <FileText className="h-4 w-4" />
                    JSON Data
                  </div>
                </SelectItem>
                <SelectItem value="csv">
                  <div className="flex items-center gap-2">
                    <FileText className="h-4 w-4" />
                    CSV Data
                  </div>
                </SelectItem>
              </SelectContent>
            </Select>
          </div>

          <div className="text-sm text-muted-foreground">
            {exportFormat === 'pdf' && (
              <p>Generate a professional PDF report with complete verification details, sources, and analysis.</p>
            )}
            {exportFormat === 'json' && (
              <p>Export structured data in JSON format for integration with other systems.</p>
            )}
            {exportFormat === 'csv' && (
              <p>Export data in CSV format for spreadsheet analysis and reporting.</p>
            )}
          </div>

          <Button 
            onClick={handleExport} 
            disabled={exporting}
            className="w-full"
            size="lg"
          >
            {exporting ? (
              <>
                <Loader2 className="h-4 w-4 mr-2 animate-spin" />
                Generating {exportFormat.toUpperCase()}...
              </>
            ) : (
              <>
                <Download className="h-4 w-4 mr-2" />
                Export {exportFormat.toUpperCase()}
              </>
            )}
          </Button>
        </div>
      </CardContent>
    </Card>
  );
}