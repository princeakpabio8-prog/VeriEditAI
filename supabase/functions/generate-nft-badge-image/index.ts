import { serve } from "https://deno.land/std@0.177.0/http/server.ts";
import { createClient } from 'https://esm.sh/@supabase/supabase-js@2';

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { badge_id, claim_text, trust_score, rarity_tier } = await req.json();
    
    if (!badge_id || !claim_text || !trust_score) {
      throw new Error('Missing required parameters');
    }

    const OPENAI_API_KEY = Deno.env.get('OPENAI_API_KEY');
    if (!OPENAI_API_KEY) {
      throw new Error('OPENAI_API_KEY not configured');
    }

    console.log(`🎨 Generating NFT badge image for: ${badge_id}`);

    // Create a detailed prompt for high-quality NFT badge image
    const rarityColors = {
      'LEGENDARY': 'glowing gold and radiant orange with divine sparkles',
      'EPIC': 'vibrant purple and magenta with mystical aura',
      'RARE': 'brilliant blue and cyan with electric energy',
      'UNCOMMON': 'emerald green and teal with nature vibes',
      'COMMON': 'silver and white with clean elegance'
    };

    const color = rarityColors[rarity_tier as keyof typeof rarityColors] || rarityColors.COMMON;

    const prompt = `Create a premium NFT badge design for a truth verification certificate:
- Main theme: ${color}
- Style: Modern, sleek, professional with blockchain/tech aesthetic
- Include: Shield or badge shape with verification checkmark symbol
- Background: Gradient with subtle geometric patterns
- Add: Glowing effects, light particles, premium quality feel
- Trust score indicator showing ${trust_score}% confidence
- Text overlay: "VeriEdit Truth Badge" in elegant font
- Overall mood: Trustworthy, authoritative, high-value digital collectible
- Aspect ratio: Square (1:1), ultra high resolution, NFT-ready artwork`;

    const response = await fetch("https://api.openai.com/v1/images/generations", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${OPENAI_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "gpt-image-1",
        prompt: prompt,
        size: "1024x1024",
        quality: "high",
        response_format: "b64_json",
        n: 1
      })
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error(`❌ OpenAI API error (${response.status}):`, errorText);
      throw new Error(`OpenAI API error: ${response.status}`);
    }

    const data = await response.json();
    console.log('📦 OpenAI Response received');
    
    const imageBase64 = data.data?.[0]?.b64_json;

    if (!imageBase64) {
      console.error('❌ No image in OpenAI response');
      throw new Error('No image generated by OpenAI');
    }

    console.log('✅ Image generated successfully');

    // Upload to Supabase Storage
    const supabaseUrl = Deno.env.get('SUPABASE_URL')!;
    const supabaseKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;
    const supabase = createClient(supabaseUrl, supabaseKey);

    // Convert base64 to buffer (no data URI prefix for OpenAI b64_json)
    const imageBuffer = Uint8Array.from(atob(imageBase64), c => c.charCodeAt(0));
    
    const fileName = `badge-${badge_id}.png`;
    const filePath = `badges/${fileName}`;

    // Upload to nft-badge-images bucket
    const { data: uploadData, error: uploadError } = await supabase.storage
      .from('nft-badge-images')
      .upload(filePath, imageBuffer, {
        contentType: 'image/png',
        upsert: true
      });

    if (uploadError) {
      console.error('Upload error:', uploadError);
      return new Response(
        JSON.stringify({ 
          success: true, 
          image_url: imageBase64,
          stored: false 
        }),
        { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    // Get public URL
    const { data: { publicUrl } } = supabase.storage
      .from('nft-badge-images')
      .getPublicUrl(filePath);

    console.log(`✅ Uploaded badge image to: ${publicUrl}`);

    // Get the NFT badge record to access metadata_uri
    const { data: badgeRecord, error: badgeError } = await supabase
      .from('nft_badges')
      .select('metadata_uri')
      .eq('id', badge_id)
      .single();

    if (badgeError || !badgeRecord) {
      console.error('❌ Could not find badge record');
      return new Response(
        JSON.stringify({ 
          success: true, 
          image_url: publicUrl,
          stored: true,
          metadata_updated: false 
        }),
        { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    // Download the existing metadata JSON
    const metadataResponse = await fetch(badgeRecord.metadata_uri);
    if (!metadataResponse.ok) {
      console.error('❌ Could not fetch existing metadata');
      return new Response(
        JSON.stringify({ 
          success: true, 
          image_url: publicUrl,
          stored: true,
          metadata_updated: false 
        }),
        { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const existingMetadata = await metadataResponse.json();
    
    // Update the image URL in the metadata
    existingMetadata.image = publicUrl;
    
    // Re-upload the updated metadata
    const metadataFileName = badgeRecord.metadata_uri.split('/').pop();
    const { error: metadataError } = await supabase.storage
      .from('nft-metadata')
      .update(metadataFileName, JSON.stringify(existingMetadata, null, 2), {
        contentType: 'application/json',
        upsert: true
      });

    if (metadataError) {
      console.error('❌ Failed to update metadata:', metadataError);
    } else {
      console.log('✅ Metadata updated with new image URL');
    }

    return new Response(
      JSON.stringify({ 
        success: true, 
        image_url: publicUrl,
        stored: true 
      }),
      { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    );

  } catch (error) {
    console.error('❌ Error generating NFT badge image:', error);
    
    return new Response(
      JSON.stringify({ 
        success: false, 
        error: error.message,
        details: error.stack
      }),
      { 
        status: 500,
        headers: { ...corsHeaders, 'Content-Type': 'application/json' } 
      }
    );
  }
});
